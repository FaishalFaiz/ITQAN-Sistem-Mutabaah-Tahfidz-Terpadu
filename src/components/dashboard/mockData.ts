// Helper konversi interval ke tanggal riil ISO
function getPastDateISO(offsetStr: string): { iso: string; formatted: string } {
  const now = new Date();
  const parts = offsetStr.split(' ');
  const val = parseInt(parts[0], 10) || 1;
  const unit = parts[1] || 'days';

  if (unit.startsWith('hour')) {
    now.setHours(now.getHours() - val);
  } else if (unit.startsWith('day')) {
    now.setDate(now.getDate() - val);
  } else if (unit.startsWith('month')) {
    now.setMonth(now.getMonth() - val);
  }

  const iso = now.toISOString();
  const formatted = new Intl.DateTimeFormat('id-ID', {
    day: 'numeric',
    month: 'short',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
  }).format(now) + ' WIB';

  return { iso, formatted };
}

