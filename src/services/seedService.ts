/**
 * Seed data halaqoh preview & 20 santri ke storage lokal & cloud Supabase
 */
export async function seedPreviewData(): Promise<{ success: boolean; message: string }> {
  try {
    // 1. Simpan room halaqoh ke allRooms
    const allRooms = storageService.getAllHalaqahRooms().filter((r) => r.id !== PREVIEW_HALAQAH_ID);
    const scope = storageService.getActiveUserScope();
    const rawUserId = scope.replace(/^u_/, '');

    const roomToSave: HalaqahGroup = {
      ...PREVIEW_HALAQAH,
      creatorId: rawUserId || 'system',
      memberIds: [scope, rawUserId, 'system'],
    };

    storageService.saveAllHalaqahRooms([roomToSave, ...allRooms]);

    // Tambahkan ke ID room milik user ini & bersihkan dari left IDs
    const userIds = storageService.getUserHalaqahIds();
    if (!userIds.includes(PREVIEW_HALAQAH_ID)) {
      storageService.saveUserHalaqahIds([PREVIEW_HALAQAH_ID, ...userIds]);
    }
    const leftKey = storageService.getScopedKey('itqan_left_halaqah_ids');
    const rawLeft = localStorage.getItem(leftKey);
    if (rawLeft) {
      const leftArr: string[] = JSON.parse(rawLeft);
      localStorage.setItem(
        leftKey,
        JSON.stringify(leftArr.filter((id) => id !== PREVIEW_HALAQAH_ID))
      );
    }

    // 2. Simpan 20 santri preview (timpa santri preview lama jika ada)
    const currentSantri = storageService.getSantriList().filter((s) => s.halaqahId !== PREVIEW_HALAQAH_ID);
    const combinedSantri = [...PREVIEW_SANTRI_LIST, ...currentSantri];
    storageService.saveSantriList(combinedSantri);

    // 3. Simpan catatan setoran
    const previewRecords = generatePreviewSetoranRecords();
    const currentRecords = storageService.getSetoranRecords().filter(
      (r) => !PREVIEW_SANTRI_LIST.some((s) => s.id === r.santriId)
    );
    const combinedRecords = [...previewRecords, ...currentRecords];
    const setoranKey = storageService.getScopedKey('itqan_setoran_records');
    localStorage.setItem(setoranKey, JSON.stringify(combinedRecords));

    // 4. Jadikan Halaqoh Preview sebagai halaqoh aktif
    storageService.setActiveHalaqah(PREVIEW_HALAQAH_ID);

    // 5. Dorong ke Supabase cloud di background jika online
    syncService.pushHalaqah(roomToSave);
    for (const s of PREVIEW_SANTRI_LIST) {
      syncService.pushSantri(s);
    }
    for (const r of previewRecords) {
      syncService.pushSetoran(r);
    }

    emitChange('preview_data_seeded');
    return {
      success: true,
      message: 'Halaqoh Preview (Al-Fath) dan 20 Santri berhasil dimuat!',
    };
  } catch (err: unknown) {
    const message = err instanceof Error ? err.message : 'Gagal memuat data preview.';
    return {
      success: false,
      message,
    };
  }
}
